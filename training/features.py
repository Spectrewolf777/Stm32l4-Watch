"""Log-mel feature extraction.

Written in plain numpy on purpose: firmware/audio_features.c implements the
exact same maths with CMSIS-DSP, and the mel filter weights + normalisation
constants are exported from here into C, so the MCU sees the same numbers the
network was trained on. (Using librosa in training and something else on the
MCU is the #1 reason these projects work on the PC and fail on the device.)
"""
import numpy as np

from config import SAMPLE_RATE, N_FFT, HOP, N_MELS, N_FRAMES, CLIP_LEN, FMIN, FMAX, LOG_EPS


def _hz_to_mel(f):
    return 2595.0 * np.log10(1.0 + f / 700.0)


def _mel_to_hz(m):
    return 700.0 * (10.0 ** (m / 2595.0) - 1.0)


def hann_window():
    n = np.arange(N_FFT)
    return (0.5 - 0.5 * np.cos(2.0 * np.pi * n / N_FFT)).astype(np.float32)  # periodic Hann


def mel_filterbank():
    n_bins = N_FFT // 2 + 1
    bin_hz = np.arange(n_bins) * SAMPLE_RATE / N_FFT
    hz = _mel_to_hz(np.linspace(_hz_to_mel(FMIN), _hz_to_mel(FMAX), N_MELS + 2))
    fb = np.zeros((N_MELS, n_bins), np.float32)
    for m in range(N_MELS):
        lo, c, hi = hz[m], hz[m + 1], hz[m + 2]
        up = (bin_hz - lo) / (c - lo)
        down = (hi - bin_hz) / (hi - c)
        fb[m] = np.maximum(0.0, np.minimum(up, down))
    assert (fb.sum(axis=1) > 0).all(), "empty mel filter - lower N_MELS or raise FMIN"
    return fb


_WINDOW = hann_window()
_MEL_FB = mel_filterbank()


def log_mel(clips):
    """clips: float32 array (B, CLIP_LEN) or (CLIP_LEN,), values in [-1, 1].
    returns float32 (B, N_FRAMES, N_MELS) un-normalised log-mel."""
    clips = np.atleast_2d(np.asarray(clips, np.float32))
    assert clips.shape[1] == CLIP_LEN, clips.shape
    idx = np.arange(N_FFT)[None, :] + HOP * np.arange(N_FRAMES)[:, None]
    out = np.empty((clips.shape[0], N_FRAMES, N_MELS), np.float32)
    for s in range(0, len(clips), 512):              # chunked to bound memory
        frames = clips[s:s + 512][:, idx] * _WINDOW    # (b, F, N_FFT)
        spec = np.fft.rfft(frames, axis=-1)
        power = (spec.real ** 2 + spec.imag ** 2).astype(np.float32)
        out[s:s + 512] = np.log(power @ _MEL_FB.T + LOG_EPS)
    return out


def _c_floats(values, per_line=8):
    vals = [f"{v:.9g}f" for v in np.asarray(values, np.float64).ravel()]
    return ",\n".join("    " + ", ".join(vals[i:i + per_line]) for i in range(0, len(vals), per_line))


def write_c_files(out_dir, classes, mean, std):
    """Writes model_config.h and model_tables.c for the firmware."""
    starts, lens, offs, weights = [], [], [], []
    for m in range(N_MELS):
        nz = np.nonzero(_MEL_FB[m])[0]
        starts.append(int(nz[0]))
        lens.append(int(nz[-1] - nz[0] + 1))
        offs.append(len(weights))
        weights.extend(_MEL_FB[m, nz[0]:nz[-1] + 1].tolist())
    inv_std = 1.0 / np.asarray(std)
    bg_index = classes.index("background")

    with open(f"{out_dir}/model_config.h", "w") as f:
        f.write(f"""/* AUTO-GENERATED by train.py - do not edit. Must match the network you import into Cube.AI. */
#ifndef MODEL_CONFIG_H
#define MODEL_CONFIG_H
#include <stdint.h>

#define AF_SAMPLE_RATE   {SAMPLE_RATE}
#define AF_N_FFT         {N_FFT}
#define AF_HOP           {HOP}
#define AF_N_MELS        {N_MELS}
#define AF_N_FRAMES      {N_FRAMES}
#define AF_LOG_EPS       {LOG_EPS:.9g}f
#define AF_N_CLASSES     {len(classes)}
#define AF_CLASS_BACKGROUND {bg_index}
#define AF_MEL_WEIGHTS_LEN  {len(weights)}

""")
        for i, c in enumerate(classes):
            f.write(f"#define AF_CLASS_{c.upper()} {i}\n")
        f.write("""
extern const uint16_t af_mel_start[AF_N_MELS];
extern const uint16_t af_mel_len[AF_N_MELS];
extern const uint16_t af_mel_offset[AF_N_MELS];
extern const float    af_mel_weights[AF_MEL_WEIGHTS_LEN];
extern const float    af_feat_mean[AF_N_MELS];
extern const float    af_feat_inv_std[AF_N_MELS];
extern const char *const af_class_names[AF_N_CLASSES];

#endif
""")

    with open(f"{out_dir}/model_tables.c", "w") as f:
        f.write('/* AUTO-GENERATED by train.py - do not edit. */\n#include "model_config.h"\n\n')
        f.write("const uint16_t af_mel_start[AF_N_MELS] = {" + ", ".join(map(str, starts)) + "};\n")
        f.write("const uint16_t af_mel_len[AF_N_MELS] = {" + ", ".join(map(str, lens)) + "};\n")
        f.write("const uint16_t af_mel_offset[AF_N_MELS] = {" + ", ".join(map(str, offs)) + "};\n")
        f.write("const float af_mel_weights[AF_MEL_WEIGHTS_LEN] = {\n" + _c_floats(weights) + "\n};\n")
        f.write("const float af_feat_mean[AF_N_MELS] = {\n" + _c_floats(mean) + "\n};\n")
        f.write("const float af_feat_inv_std[AF_N_MELS] = {\n" + _c_floats(inv_std) + "\n};\n")
        f.write("const char *const af_class_names[AF_N_CLASSES] = {"
                + ", ".join(f'"{c}"' for c in classes) + "};\n")


def write_test_vector(out_dir, clip_int16, features_norm, probs):
    """One known clip + the expected output, so you can check the C feature code
    on the real MCU produces the same numbers as Python."""
    with open(f"{out_dir}/test_vector.h", "w") as f:
        f.write("/* AUTO-GENERATED by train.py. Include in ONE .c file only. */\n#include <stdint.h>\n")
        f.write(f"#define TV_LEN {len(clip_int16)}\n")
        vals = [str(int(v)) for v in clip_int16]
        f.write("static const int16_t tv_audio[TV_LEN] = {\n" +
                ",\n".join("    " + ", ".join(vals[i:i + 16]) for i in range(0, len(vals), 16)) + "\n};\n")
        f.write("static const float tv_features[AF_N_FRAMES * AF_N_MELS] = {\n" + _c_floats(features_norm) + "\n};\n")
        f.write("static const float tv_probs[AF_N_CLASSES] = {" + ", ".join(f"{p:.6f}f" for p in probs) + "};\n")
